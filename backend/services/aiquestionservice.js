

const Groq = require("groq-sdk");

const groq = new Groq({
  apiKey: process.env.GROQ_API_KEY
});

const generateQuestions = async ({
  role,
  round,
  difficulty,
  count,
  topics
}) => {
  if (!Number.isInteger(count) || count < 1) {
    throw new Error("Question count must be a positive integer");
  }

  if (!Array.isArray(topics) || topics.length === 0) {
    throw new Error("At least one topic is required");
  }

  const allQuestions = [];
  const questionTexts = new Set();
  const batchSize = 5;

  for (let i = 0; i < count; i += batchSize) {
    const currentBatch = Math.min(batchSize, count - i);

    console.log(`Generating batch: ${currentBatch} questions`);

    const prompt = `
You are an expert recruitment assessment generator.

Generate exactly ${currentBatch} original MCQ questions.

JOB ROLE: ${role}
INTERVIEW ROUND: ${round}
DIFFICULTY: ${difficulty}
TOPICS: ${topics.join(", ")}

RULES:
1. Generate exactly ${currentBatch} questions.
2. Each question must have exactly 4 options.
3. Exactly one option must be correct.
4. The correctAnswer must exactly match the text of the correct option.
5. Include a short, factually correct explanation.
6. Use professional English.
7. Match the requested difficulty.
8. Do not repeat questions or options.
9. Return valid JSON only.

Required JSON structure:

{
  "questions": [
    {
      "questionText": "Question here",
      "topic": "Logical Reasoning",
      "options": [
        {"text": "Option A", "isCorrect": false},
        {"text": "Option B", "isCorrect": true},
        {"text": "Option C", "isCorrect": false},
        {"text": "Option D", "isCorrect": false}
      ],
      "correctAnswer": "Option B",
      "explanation": "Short explanation"
    }
  ]
}
`;

    const response = await groq.chat.completions.create({
      model: process.env.GROQ_MODEL || "openai/gpt-oss-120b",

      messages: [
        {
          role: "system",
          content: "Generate recruitment MCQs. Return valid JSON only."
        },
        {
          role: "user",
          content: prompt
        }
      ],

      temperature: 0.3,
      max_completion_tokens: 4096,

      response_format: {
        type: "json_object"
      }
    });

    const choice = response.choices?.[0];

    if (!choice || !choice.message?.content) {
      throw new Error("AI returned an empty response");
    }

    if (choice.finish_reason === "length") {
      throw new Error("AI response was incomplete. Please try again.");
    }

    const result = JSON.parse(choice.message.content);

    if (
      !Array.isArray(result.questions) ||
      result.questions.length !== currentBatch
    ) {
      throw new Error(
        `Expected ${currentBatch} questions but received ${
          result.questions?.length || 0
        }`
      );
    }

    for (const q of result.questions) {
      if (
        typeof q.questionText !== "string" ||
        !q.questionText.trim() ||
        typeof q.topic !== "string" ||
        !q.topic.trim() ||
        !Array.isArray(q.options) ||
        q.options.length !== 4 ||
        typeof q.explanation !== "string" ||
        !q.explanation.trim()
      ) {
        throw new Error("Invalid question structure generated by AI");
      }

      // Validate all four options
      const validOptions = q.options.every(
        option =>
          typeof option.text === "string" &&
          option.text.trim().length > 0 &&
          typeof option.isCorrect === "boolean"
      );

      if (!validOptions) {
        throw new Error("Invalid option structure generated by AI");
      }

      // Prevent duplicate options
      const optionTexts = q.options.map(
        option => option.text.trim().toLowerCase()
      );

      if (new Set(optionTexts).size !== 4) {
        throw new Error("Duplicate options generated by AI");
      }

      // Exactly one correct option
      const correctOptions = q.options.filter(
        option => option.isCorrect === true
      );

      if (correctOptions.length !== 1) {
        throw new Error("Question must have exactly one correct option");
      }

      // Correct answer must match the correct option
      if (
        typeof q.correctAnswer !== "string" ||
        q.correctAnswer.trim() !== correctOptions[0].text.trim()
      ) {
        throw new Error("Correct answer does not match the correct option");
      }

      // Prevent duplicate questions across batches
      const normalizedQuestion = q.questionText.trim().toLowerCase();

      if (questionTexts.has(normalizedQuestion)) {
        throw new Error("Duplicate question generated by AI");
      }

      questionTexts.add(normalizedQuestion);
      allQuestions.push(q);
    }
  }

  console.log("Total generated:", allQuestions.length);

  if (allQuestions.length !== count) {
    throw new Error("Final question count does not match requested count");
  }

  return allQuestions;
};

module.exports = generateQuestions;
