

const Groq = require("groq-sdk");

const groq = new Groq({
  apiKey: process.env.GROQ_API_KEY
});

const generateQuestions = async ({
  role,
  round,
  difficulty,
  count,
  topics
}) => {
  const allQuestions = [];
  const batchSize = 5;

  for (let i = 0; i < count; i += batchSize) {
    const currentBatch = Math.min(batchSize, count - i);

    console.log(`Generating batch: ${currentBatch} questions`);

    const prompt = `
You are an expert recruitment assessment generator.

Generate exactly ${currentBatch} original MCQ questions.

JOB ROLE: ${role}
INTERVIEW ROUND: ${round}
DIFFICULTY: ${difficulty}
TOPICS: ${topics.join(", ")}

RULES:
1. Generate exactly ${currentBatch} questions.
2. Each question must have exactly 4 options.
3. Exactly one option must be correct.
4. Include a short explanation.
5. Use professional English.
6. Questions must match the requested difficulty.
7. Return JSON only.

Required JSON structure:

{
  "questions": [
    {
      "questionText": "Question here",
      "topic": "Logical Reasoning",
      "options": [
        {"text": "Option A", "isCorrect": false},
        {"text": "Option B", "isCorrect": true},
        {"text": "Option C", "isCorrect": false},
        {"text": "Option D", "isCorrect": false}
      ],
      "correctAnswer": "Option B",
      "explanation": "Short explanation",
      "marks": 1,
      "negativeMarks": 0
    }
  ]
}
`;

    const response = await groq.chat.completions.create({
      model: process.env.GROQ_MODEL || "openai/gpt-oss-120b",

      messages: [
        {
          role: "system",
          content: "Generate recruitment MCQs. Return valid JSON only."
        },
        {
          role: "user",
          content: prompt
        }
      ],

      temperature: 0.3,

      max_completion_tokens: 4096,

      response_format: {
        type: "json_object"
      }
    });

    const content = response.choices[0].message.content;

    console.log("Finish reason:", response.choices[0].finish_reason);

    if (!content) {
      throw new Error("AI returned an empty response");
    }

    const result = JSON.parse(content);

    if (
      !Array.isArray(result.questions) ||
      result.questions.length !== currentBatch
    ) {
      throw new Error(
        `Expected ${currentBatch} questions but received ${
          result.questions?.length || 0
        }`
      );
    }

    // Validate each question
    result.questions.forEach((q) => {
      if (
        !q.questionText ||
        !q.topic ||
        !Array.isArray(q.options) ||
        q.options.length !== 4 ||
        q.options.filter(o => o.isCorrect === true).length !== 1 ||
        !q.explanation ||
        !q.options.some(o => o.text === q.correctAnswer)
      ) {
        throw new Error("Invalid question generated by AI");
      }
    });

    allQuestions.push(...result.questions);
  }

  console.log("Total generated:", allQuestions.length);

  if (allQuestions.length !== count) {
    throw new Error("Final question count does not match requested count");
  }

  return allQuestions;
};

module.exports = generateQuestions;
